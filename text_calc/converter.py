closed_parens_set = {
    "закрывающаяся скобка", "закрывающая скобка",
    "скобка закрывается", "закрытая скобка"
}

def get_type(word):
    if word in string_to_number_dictionary:
        return tokens.NUMBER
    if word in operators_dictionary:
        return tokens.OPERATOR
    if word in opened_parens_set:
        return tokens.OPENED_PAREN
    if word in closed_parens_set:
        return tokens.CLOSED_PAREN
    if word == "END":
        return tokens.END

    return None

def get_number(number):
    if number in string_to_number_dictionary:
        return string_to_number_dictionary[number]

def get_operator(operator):
    return operators_dictionary[operator]